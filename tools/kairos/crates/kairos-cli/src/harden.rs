//! `kairos harden` — render the hardening-status block into a README from its
//! `docs/plans/use-protection-please.md`.
//!
//! The plan file is the single source of truth; this verb is the only writer
//! of the README block. It is idempotent: running it twice produces a
//! byte-identical README, which is what makes `--check` usable as a CI gate.
//!
//! A Rust port of the `use-protection-please` skill's
//! `scripts/render_readme_table.py` (2026-08-18), rendering the block the
//! skill's `templates/readme-table.md` specifies, so plan files stay
//! interchangeable with every other unit in the portfolio. Glyphs are written
//! as `\u{..}` escapes so this file stays ASCII.

use std::{
    collections::BTreeMap,
    fs,
    path::{Path, PathBuf},
};

use crate::{Manifest, Result, fail, has_flag, option};

pub(crate) const PLAN_NAME: &str = "use-protection-please.md";

const BEGIN: &str = "<!-- HARDENING-TABLE:BEGIN";
const END: &str = "<!-- HARDENING-TABLE:END -->";
const BEGIN_LINE: &str = "<!-- HARDENING-TABLE:BEGIN generated by use-protection-please \u{2014} edit docs/plans/use-protection-please.md, not this block -->";
const BAR_CELLS: usize = 20;
const STAR: char = '\u{2605}';
const FULL: char = '\u{2588}';
const EMPTY: char = '\u{2591}';
const GLYPH_DONE: &str = "\u{2705}";
const GLYPH_SCHEDULED: &str = "\u{1F5D3}";
const GLYPH_OPEN: &str = "\u{2B1C}";
const DASH: &str = "\u{2014}";
const DOT: &str = "\u{b7}";

