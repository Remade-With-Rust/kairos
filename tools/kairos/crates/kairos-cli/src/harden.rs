#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Status {
    Completed,
    Scheduled,
    Incomplete,
    NotApplicable,
}

impl Status {
    fn parse(raw: &str) -> Result<Self> {
        let token: String = raw
            .trim()
            .trim_matches(|c: char| matches!(c, '`' | '*' | '_' | ' '))
            .trim_end_matches('.')
            .chars()
            .filter(|c| c.is_ascii_alphabetic() || *c == '/' || *c == ' ')
            .collect();
        let folded: String = token.to_lowercase().chars().filter(|c| *c != ' ').collect();
        match folded.as_str() {
            "na" | "n/a" | "notapplicable" => Ok(Self::NotApplicable),
            "completed" => Ok(Self::Completed),
            "scheduled" => Ok(Self::Scheduled),
            "incomplete" | "" => Ok(Self::Incomplete),
            _ => fail(format!(
                "unrecognised status {raw:?} (expected one of Completed, Scheduled, Incomplete, N/A)"
            )),
        }
    }
}

#[derive(Debug, Clone)]
struct Row {
    id: String,
    gate: String,
    status: Status,
    target: String,
    phase: String,
    star: bool,
}

#[derive(Debug, Default)]
struct Counts {
    completed: usize,
    scheduled: usize,
    incomplete: usize,
    na: usize,
}

impl Counts {
    fn add(&mut self, s: Status) {
        match s {
            Status::Completed => self.completed += 1,
            Status::Scheduled => self.scheduled += 1,
            Status::Incomplete => self.incomplete += 1,
            Status::NotApplicable => self.na += 1,
        }
    }
}

struct Plan {
    meta: BTreeMap<String, String>,
    rows: Vec<Row>,
    warnings: Vec<String>,
}

// ---------------------------------------------------------------- parsing --

fn split_row(line: &str) -> Vec<String> {
    let body = line.trim();
    let body = body.strip_prefix('|').unwrap_or(body);
    let body = body.strip_suffix('|').unwrap_or(body);
    body.split('|').map(|c| c.trim().to_owned()).collect()
}

fn is_gate_id(cell: &str) -> bool {
    let mut chars = cell.chars();
    matches!(chars.next(), Some('H' | 'C'))
        && chars.next() == Some('-')
        && chars.clone().count() > 0
        && chars.all(|c| c.is_ascii_digit())
}

/// `**Key**: value` header lines above the checklist.
fn meta_line(line: &str) -> Option<(String, String)> {
    let rest = line.strip_prefix("**")?;
    let end = rest.find("**")?;
    let key = &rest[..end];
    if key.is_empty()
        || !key
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == ' ' || c == '.')
    {
        return None;
    }
    let value = rest[end + 2..].trim_start();
    let value = value.strip_prefix(':').unwrap_or(value).trim();
    Some((key.trim().to_lowercase(), value.to_owned()))
}

fn parse_plan(path: &Path) -> Result<Plan> {
    let text = fs::read_to_string(path)?;
    let mut meta = BTreeMap::new();
    let mut rows: Vec<Row> = Vec::new();
    let mut warnings = Vec::new();
    let mut phase = "Unfiled".to_owned();
    let mut in_checklist = false;

    for line in text.lines() {
        if line.starts_with("## ") {
            in_checklist = line.trim().to_lowercase().starts_with("## checklist");
            continue;
        }
        if let Some(h) = line.strip_prefix("### ") {
            phase = h.trim().to_owned();
            continue;
        }
        if rows.is_empty() {
            if let Some((k, v)) = meta_line(line) {
                meta.entry(k).or_insert(v);
            }
        }
        if !in_checklist || !line.trim_start().starts_with('|') {
            continue;
        }
        let cells = split_row(line);
        let Some(id) = cells.first() else { continue };
        if !is_gate_id(id) {
            continue;
        }
        if cells.len() < 3 {
            return fail(format!(
                "{}: malformed row: {}",
                path.display(),
                line.trim()
            ));
        }
        if rows.iter().any(|r| &r.id == id) {
            return fail(format!("{}: duplicate gate {id}", path.display()));
        }
        let gate = cells.get(1).cloned().unwrap_or_default();
        let mut status = Status::parse(cells.get(2).map_or("", String::as_str))?;
        let evidence = cells.get(3).cloned().unwrap_or_default();
        let target = cells.get(4).cloned().unwrap_or_default();
        if status == Status::Scheduled && target.is_empty() {
            warnings.push(format!(
                "{id}: Scheduled with no Target date -> counted Incomplete"
            ));
            status = Status::Incomplete;
        }
        if status == Status::NotApplicable && evidence.is_empty() {
            warnings.push(format!("{id}: N/A with no reason in Evidence"));
        }
        rows.push(Row {
            id: id.clone(),
            star: gate.contains(STAR),
            gate,
            status,
            target,
            phase: phase.clone(),
        });
    }
    if rows.is_empty() {
        return fail(format!(
            "{}: no gate rows found (expected rows starting '| H-01 |')",
            path.display()
        ));
    }
    Ok(Plan {
        meta,
        rows,
        warnings,
    })
}

