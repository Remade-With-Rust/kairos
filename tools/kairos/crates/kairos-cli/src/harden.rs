/// Keep the label at the head of a prose header field, drop the gloss after it.
fn lead_token(raw: &str, default: &str, stops: &[&str]) -> String {
    let mut val = raw.trim().to_owned();
    for sep in stops {
        if let Some(i) = val.find(sep) {
            val.truncate(i);
        }
    }
    val.split_whitespace()
        .next()
        .map_or_else(|| default.to_owned(), str::to_owned)
}

fn phase_label(heading: &str) -> String {
    let rest = heading.strip_prefix("Phase").unwrap_or(heading);
    rest.trim().to_owned()
}

fn clean_gate(gate: &str) -> String {
    gate.replace(STAR, "").trim().to_owned()
}

fn progress_bar(fraction: f64) -> String {
    #[allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]
    let filled = ((fraction * BAR_CELLS as f64) as usize).min(BAR_CELLS);
    let mut s = String::with_capacity(BAR_CELLS * 3);
    for _ in 0..filled {
        s.push(FULL);
    }
    for _ in filled..BAR_CELLS {
        s.push(EMPTY);
    }
    s
}

/// The plan's path relative to the README's directory, forward slashes.
fn rel_link(readme: &Path, plan: &Path) -> String {
    let base = readme.parent().unwrap_or_else(|| Path::new("."));
    let (Ok(base), Ok(plan_abs)) = (base.canonicalize(), plan.canonicalize()) else {
        return plan.to_string_lossy().replace('\\', "/");
    };
    match plan_abs.strip_prefix(&base) {
        Ok(rel) => rel.to_string_lossy().replace('\\', "/"),
        Err(_) => plan.to_string_lossy().replace('\\', "/"),
    }
}

fn compliance_rows(plan: &Plan) -> Vec<(String, usize, usize, &'static str)> {
    let declared = plan
        .meta
        .get("compliance")
        .map(|s| s.to_lowercase())
        .unwrap_or_default();
    let declared = if declared.trim().starts_with("none") {
        declared.split('-').next().unwrap_or_default().to_owned()
    } else {
        declared
    };
    let mut out = Vec::new();
    for (fid, label, gates) in FRAMEWORKS {
        if !declared.contains(fid) {
            continue;
        }
        let live: Vec<&Row> = gates
            .split_whitespace()
            .filter_map(|g| plan.rows.iter().find(|r| r.id == g))
            .filter(|r| r.status != Status::NotApplicable)
            .collect();
        if live.is_empty() {
            continue;
        }
        let met = live
            .iter()
            .filter(|r| r.status == Status::Completed)
            .count();
        let mark = if met == live.len() {
            GLYPH_DONE
        } else if live.iter().any(|r| r.status == Status::Scheduled) {
            GLYPH_SCHEDULED
        } else {
            GLYPH_OPEN
        };
        out.push((label.to_owned(), met, live.len(), mark));
    }
    out
}

fn render_block(
    plan: &Plan,
    readme: &Path,
    plan_path: &Path,
    link: &str,
    architect: &str,
) -> String {
    let mut counts = Counts::default();
    let mut per_phase: Vec<(String, Counts)> = Vec::new();
    for row in &plan.rows {
        counts.add(row.status);
        match per_phase.iter_mut().find(|(p, _)| *p == row.phase) {
            Some((_, c)) => c.add(row.status),
            None => {
                let mut c = Counts::default();
                c.add(row.status);
                per_phase.push((row.phase.clone(), c));
            }
        }
    }
    let tracked = counts.completed + counts.scheduled + counts.incomplete;
    #[allow(clippy::cast_precision_loss)]
    let pct = if tracked == 0 {
        0.0
    } else {
        counts.completed as f64 / tracked as f64
    };
    let stars: Vec<&Row> = plan
        .rows
        .iter()
        .filter(|r| r.star && r.status != Status::NotApplicable)
        .collect();
    let stars_done = stars
        .iter()
        .filter(|r| r.status == Status::Completed)
        .count();

    let meta = |k: &str| plan.meta.get(k).map_or("", String::as_str);
    let tier = lead_token(
        meta("tier"),
        "unspecified",
        &[" - ", " \u{2014} ", " (", ","],
    );
    let audited = lead_token(meta("audited"), "unrecorded", &[" by "]);
    let depth = lead_token(meta("audit depth"), "", &[" - ", " \u{2014} ", " (", ","]);
    let audited_str = if depth.is_empty() {
        audited
    } else {
        format!("{audited} ({depth})")
    };
    let link = if link.is_empty() {
        rel_link(readme, plan_path)
    } else {
        link.to_owned()
    };

    #[allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]
    let pct_int = (pct * 100.0).round() as usize;
    let mut out = vec![
        BEGIN_LINE.to_owned(),
        "## Hardening status".to_owned(),
        String::new(),
        format!(
            "**Tier** {tier} {DOT} **Audited** {audited_str} {DOT} **v1.0.0 gates** {stars_done}/{} {DOT} [Full checklist]({link})",
            stars.len()
        ),
        String::new(),
        format!(
            "`{}` **{pct_int}%** &nbsp;{DOT}&nbsp; {} Completed {DOT} {} Scheduled {DOT} {} Incomplete {DOT} {} N/A",
            progress_bar(pct),
            counts.completed,
            counts.scheduled,
            counts.incomplete,
            counts.na
        ),
        String::new(),
        format!(
            "| Phase | {GLYPH_DONE} Completed | {GLYPH_SCHEDULED} Scheduled | {GLYPH_OPEN} Incomplete | {DOT} N/A |"
        ),
        "|---|--:|--:|--:|--:|".to_owned(),
    ];
    for (phase, c) in &per_phase {
        out.push(format!(
            "| {} | {} | {} | {} | {} |",
            phase_label(phase),
            c.completed,
            c.scheduled,
            c.incomplete,
            c.na
        ));
    }
    out.push(format!(
        "| **Total** | **{}** | **{}** | **{}** | **{}** |",
        counts.completed, counts.scheduled, counts.incomplete, counts.na
    ));

    let mut upcoming: Vec<&Row> = plan
        .rows
        .iter()
        .filter(|r| r.status == Status::Scheduled)
        .collect();
    upcoming.sort_by(|a, b| (&a.target, &a.id).cmp(&(&b.target, &b.id)));
    upcoming.truncate(3);
    if !upcoming.is_empty() {
        let items: Vec<String> = upcoming
            .iter()
            .map(|r| format!("{} {} ({})", r.id, clean_gate(&r.gate), r.target))
            .collect();
        out.push(String::new());
        out.push(format!(
            "**Next up** {DASH} {}",
            items.join(&format!(" {DOT} "))
        ));
    }

    let comp = compliance_rows(plan);
    if !comp.is_empty() {
        out.push(String::new());
        out.push(format!(
            "**Compliance** {DASH} *technical controls evidenced by this audit. NOT a certification, an attestation, or an auditor's opinion.*"
        ));
        out.push(String::new());
        out.push("| Framework | Technical controls met | |".to_owned());
        out.push("|---|--:|:--|".to_owned());
        for (label, met, total, mark) in comp {
            out.push(format!("| {label} | {met} / {total} | {mark} |"));
        }
    }

    let who = if architect.is_empty() {
        meta("architect").trim().to_owned()
    } else {
        architect.trim().to_owned()
    };
    if !who.is_empty() {
        out.push(String::new());
        out.push(format!("**Architect** {DASH} {who}"));
    }
    out.push(END.to_owned());
    out.join("\n")
}

fn splice(readme: &str, block: &str) -> String {
    if let (Some(start), Some(end)) = (readme.find(BEGIN), readme.find(END)) {
        if end > start {
            return format!("{}{block}{}", &readme[..start], &readme[end + END.len()..]);
        }
    }
    let body = readme.trim_end_matches('\n');
    if body.is_empty() {
        format!("{block}\n")
    } else {
        format!("{body}\n\n---\n\n{block}\n")
    }
}

